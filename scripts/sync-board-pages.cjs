const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const dist = path.join(root, 'dist');
const walk = dir => fs.readdirSync(dir, {withFileTypes: true}).flatMap(entry => {
  const full = path.join(dir, entry.name);
  return entry.isDirectory() ? walk(full) : entry.name === 'index.html' ? [full] : [];
});
const decode = text => text.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'");
const pages = [{id: 'general', name: '全体', url: null}];
for (const file of walk(dist).sort()) {
  const relative = path.relative(dist, path.dirname(file)).split(path.sep).join('/');
  if ((relative === 'other/board' || relative.startsWith('other/board/'))) continue;
  const id = relative || 'home';
  let html = fs.readFileSync(file, 'utf8');
  html = html.replace(/[ \t]*<!-- page-board-assets -->[\s\S]*?<!-- \/page-board-assets -->\r?\n?/g, '')
    .replace(/[ \t]*<!-- page-board -->[\s\S]*?<!-- \/page-board -->\r?\n?/g, '');
  html = html.replace(/[ \t]*<!-- board-header-link -->[\s\S]*?<!-- \/board-header-link -->\r?\n?/g, '');
  if (id.startsWith('other/characters/')) {
    if (html !== fs.readFileSync(file, 'utf8')) fs.writeFileSync(file, html);
    continue;
  }
  const title = html.match(/<title>([^<]+)<\/title>/)?.[1];
  if (!title) throw new Error(`Missing title: ${file}`);
  const name = id === 'home' ? 'HOME' : decode(title.replace(/^万紫千紅\s*/, ''));
  pages.push({id, name, url: relative ? '/' + relative + '/' : '/'});
  const newline = html.includes('\r\n') ? '\r\n' : '\n';
  if ((html.match(/<\/main>/g) || []).length !== 1) throw new Error(`Expected one main: ${file}`);
  const assets = [
    '    <!-- page-board-assets -->',
    '    <link rel="stylesheet" href="/other/board/page-board.css?v=6">',
    `    <script src="/other/board/page-board.js?v=5" data-board-page="${id}" defer></script>`,
    '    <!-- /page-board-assets -->',
  ].join(newline) + newline;
  const section = [
    '      <!-- page-board -->',
    '      <section class="page-board" aria-labelledby="page-board-title">',
    '        <h2 id="page-board-title">このページへの投稿</h2>',
    '        <p id="page-board-status" role="status">読み込み中…</p>',
    '        <div id="page-board-posts"></div>',
    '      </section>',
    '      <!-- /page-board -->',
  ].join(newline) + newline;
  const headerLink = `<!-- board-header-link --><a class="site-home-link board-header-link" href="/other/board/?page=${encodeURIComponent(id)}">掲示板</a><!-- /board-header-link -->` + newline;
  if (!html.includes('</header>')) throw new Error(`Missing header: ${file}`);
  html = html.replace(/<header\b[\s\S]*?<\/header>/, header =>
    header.replace('</header>', headerLink + '</header>'));
  html = html.replace(/([ \t]*)<\/head>/, assets + '$1</head>')
    .replace(/([ \t]*)<\/main>/, section + '$1</main>');
  if (html !== fs.readFileSync(file, 'utf8')) fs.writeFileSync(file, html);
}
const data = JSON.stringify(pages, null, 2).replace(/</g, '\\u003c');
fs.writeFileSync(path.join(root, 'lib/board-pages.mjs'),
  '// Generated by scripts/sync-board-pages.cjs.\nexport const boardPages = ' + data + ';\n');
fs.writeFileSync(path.join(dist, 'other/board/board-pages.js'),
  '// Generated by scripts/sync-board-pages.cjs.\nwindow.BOARD_PAGES = ' + data + ';\n');
console.log(`Board destinations and previews synchronized for ${pages.length - 1} pages.`);
