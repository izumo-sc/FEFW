"""Generate the skill, combat art and magic learners page data from data/character-learnsets.json."""
import json
import re
from pathlib import Path
from common_skill_learnsets import display_ranks

LEVELS = ['E', 'E＋', 'D', 'D＋', 'C', 'C＋', 'B', 'B＋', 'A', 'A＋', 'S', 'S＋']
SKILLS = ['剣術', '槍術', '斧術', '弓術', '格闘術', '黒魔術', '白魔術', '指揮術', '歩兵術', '馬術', '重装術', '飛行術']


def collect(data):
    assert data['schemaVersion'] == 1
    groups = {skill: {} for skill in SKILLS}
    seen_ids = set()
    for character in data['characters']:
        identifier = character['id']
        assert re.fullmatch(r'[a-z][a-z0-9-]*', identifier), identifier
        assert identifier not in seen_ids, identifier
        seen_ids.add(identifier)
        for skill in SKILLS:
            ranks = display_ranks(skill, character['skills'].get(skill, {}))
            assert set(ranks) <= set(LEVELS), (identifier, skill)
            for rank in LEVELS:
                names = ranks.get(rank, [])
                assert isinstance(names, list), (identifier, skill, rank)
                seen_names = set()
                for name in names:
                    assert isinstance(name, str) and name.strip(), (identifier, skill, rank)
                    name = name.strip()
                    if name in seen_names:
                        continue
                    seen_names.add(name)
                    groups[skill].setdefault(name, []).append({
                        'id': identifier, 'name': character['name'], 'rank': rank
                    })
    return {skill: [{'name': name, 'learners': learners} for name, learners in entries.items()]
            for skill, entries in groups.items()}


def write_data(root, result):
    output = root / 'dist/other/magic-learners/learners-data.js'
    output.write_text('// Generated by scripts/sync-magic-learners.py.\nwindow.MAGIC_LEARNERS = '
                      + json.dumps(result, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    print(f'Learners updated: {sum(len(items) for items in result.values())} entries.')


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    data = json.loads((root / 'data/character-learnsets.json').read_text(encoding='utf-8'))
    write_data(root, collect(data))
