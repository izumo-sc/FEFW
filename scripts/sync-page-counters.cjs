const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const dist = path.join(root, 'dist');
function pages(dir) {
  return fs.readdirSync(dir, {withFileTypes:true}).flatMap(entry => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? pages(full) : entry.name === 'index.html' ? [full] : [];
  });
}
const ids = [];
const labels = [];
for (const file of pages(dist).sort()) {
  const relative = path.relative(dist, path.dirname(file)).split(path.sep).join('/');
  const id = relative || 'home';
  const src = (relative ? '../'.repeat(relative.split('/').length) : './') + 'page-counter.js?v=1';
  const html = fs.readFileSync(file, 'utf8');
  const newline = html.includes('\r\n') ? '\r\n' : '\n';
  const clean = html.replace(/^[ \t]*<script\b[^>]*src="[^"\n]*(?:home-counter|page-counter)\.js[^"\n]*"[^>]*><\/script>\r?\n/gm, '');
  // Character details are excluded; only their index page is counted.
  if (id.startsWith('other/characters/') || id === 'other/board') {
    if (clean !== html) fs.writeFileSync(file, clean);
    continue;
  }
  ids.push(id);
  const title = html.match(/<title>([^<]+)<\/title>/)?.[1].replace(/^万紫千紅\s*/, '');
  if (!title) throw new Error(`Missing title: ${file}`);
  labels.push([id, id === 'home' ? 'ホーム' : title]);
  const updated = clean.replace(/([ \t]*)<\/body>/, `    <script src="${src}" data-page="${id}"></script>${newline}$1</body>`);
  if (updated === clean) throw new Error(`Missing body: ${file}`);
  if (updated !== html) fs.writeFileSync(file, updated);
}
fs.mkdirSync(path.join(root, 'lib'), {recursive:true});
fs.writeFileSync(path.join(root, 'lib/counter-pages.mjs'), '// Generated by scripts/sync-page-counters.cjs. Fixed public page IDs only.\nexport const pageIds = new Set(' + JSON.stringify(ids, null, 2) + ');\n');
const quoteSql = text => "'" + text.replaceAll("'", "''") + "'";
const report = `-- Generated by scripts/sync-page-counters.cjs. Read-only report.\nWITH pages(page, name) AS (\n  VALUES\n${labels.map(pair => '    (' + pair.map(quoteSql).join(', ') + ')').join(',\n')}\n)\nSELECT pages.name AS "ページ名",\n       COALESCE(page_views.count, 0) AS "閲覧数",\n       page_views.updated_at AS "最終更新日時（UTC）"\nFROM pages\nLEFT JOIN page_views ON page_views.page = pages.page\nORDER BY "閲覧数" DESC, pages.page;\n`;
fs.mkdirSync(path.join(root, 'sql'), {recursive:true});
fs.writeFileSync(path.join(root, 'sql/page-views-ja.sql'), report);
console.log(`Counters synchronized for ${ids.length} pages.`);
